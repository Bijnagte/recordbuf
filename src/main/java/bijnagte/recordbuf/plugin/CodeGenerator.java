package bijnagte.recordbuf.plugin;

import java.util.ArrayList;
import java.util.List;

import com.google.protobuf.DescriptorProtos.FileDescriptorProto;
import com.google.protobuf.compiler.PluginProtos.CodeGeneratorRequest;
import com.google.protobuf.compiler.PluginProtos.CodeGeneratorResponse;
import com.google.protobuf.compiler.PluginProtos.CodeGeneratorResponse.Feature;

import bijnagte.recordbuf.plugin.model.FileTable;
import bijnagte.recordbuf.plugin.model.ModelLoader;
import bijnagte.recordbuf.plugin.model.ProtoFile;
import bijnagte.recordbuf.plugin.types.TypeResolver;
import bijnagte.recordbuf.plugin.writer.CodecGenerator;
import bijnagte.recordbuf.plugin.writer.EnumGenerator;
import bijnagte.recordbuf.plugin.writer.JavaWriter;
import bijnagte.recordbuf.plugin.writer.RecordGenerator;

/**
 * Drives code generation for a single {@link CodeGeneratorRequest}.
 *
 * <p>For each file in the request's {@code file_to_generate} list we produce
 * one Java source file (the record for that file's top-level types).
 * Dependencies (the other {@code proto_file} entries) are not generated,
 * but are used to build the type-resolution table.
 */
public final class CodeGenerator {

    private final FileTable table = new FileTable();

    /** Run generation; returns a response ready to serialize to the client. */
    public CodeGeneratorResponse generate(CodeGeneratorRequest request) {
        // Pass 1: load ALL files (including dependencies) into the type table.
        // Without this, we wouldn't know the Java FQNs for cross-file types.
        table.addAll(request.getProtoFileList());

        List<CodeGeneratorResponse.File> outFiles = new ArrayList<>();
        for (String fileName : request.getFileToGenerateList()) {
            outFiles.add(generateFile(fileName));
        }

        CodeGeneratorResponse.Builder resp = CodeGeneratorResponse.newBuilder();
        resp.setSupportedFeatures(Feature.FEATURE_PROTO3_OPTIONAL_VALUE);
        for (CodeGeneratorResponse.File f : outFiles) resp.addFile(f);
        return resp.build();
    }

    private CodeGeneratorResponse.File generateFile(String fileName) {
        FileDescriptorProto fdp = findByPath(fileName);
        if (fdp == null) throw new IllegalStateException("file not found: " + fileName);

        String javaPkg = javaPackage(fdp);
        ModelLoader loader = new ModelLoader(table, javaPkg);
        ProtoFile pf = loader.load(fdp);

        JavaWriter w = new JavaWriter();
        w.header("Generated by recordbuf -- DO NOT EDIT.");
        w.header("Proto: " + fileName);
        w.line("package " + javaPkg + ";");
        w.line();

        // Enum first so the record can reference it.
        for (var e : pf.enums()) {
            new EnumGenerator().write(w, e);
            w.line();
        }
        // Then each top-level message with its nested types and codec.
        for (var m : pf.messages()) {
            emitMessage(w, m, javaPkg);
            w.line();
        }

        String javaFileName = pf.fileName();
        int slash = javaFileName.lastIndexOf('/');
        if (slash >= 0) javaFileName = javaFileName.substring(slash + 1);
        // Replace .proto with .java (proto file basename).
        if (javaFileName.endsWith(".proto")) {
            javaFileName = javaFileName.substring(0, javaFileName.length() - 6) + ".java";
        }

        return CodeGeneratorResponse.File.newBuilder()
                .setName(javaFileName)   // relative to out dir; we don't put it in a subpackage dir for v1
                .setContent(w.toString())
                .build();
    }

    private void emitMessage(JavaWriter w, bijnagte.recordbuf.plugin.model.Message m, String javaPkg) {
        TypeResolver types = new TypeResolver(table, javaPkg);
        RecordGenerator rec = new RecordGenerator(types);
        CodecGenerator codec = new CodecGenerator(types);
        recordAndCodec(w, rec, codec, m, javaPkg);
    }

    private void recordAndCodec(JavaWriter w, RecordGenerator rec, CodecGenerator codec,
                                bijnagte.recordbuf.plugin.model.Message m, String javaPkg) {
        w.line("public record " + m.name() + "(");
        for (int i = 0; i < m.fields().size(); i++) {
            var f = m.fields().get(i);
            String type = resolveJavaType(m, f, javaPkg);
            String sep = (i == m.fields().size() - 1) ? "" : ",";
            w.line("    " + type + " " + f.javaName() + sep);
        }
        w.line(")");
        w.line("{");
        w.indent(w.indent() + 1);
        // Compact constructor: null-safe for Optional/List/Map fields.
        addCompactConstructor(w, m);
        // Nested messages and enums.
        for (var nested : m.nestedMessages()) {
            w.line();
            recordAndCodec(w, rec, codec, nested, javaPkg);
        }
        for (var nested : m.nestedEnums()) {
            w.line();
            new EnumGenerator().write(w, nested);
        }
        // Codec as last member so the type can reference itself.
        codec.writeCodec(w, m);
        w.indent(w.indent() - 1);
        w.line("}");
    }

    /** Emit a compact constructor that wraps nulls in Optional.empty() and
     *  unmodifiable copies for List/Map. */
    private void addCompactConstructor(JavaWriter w, bijnagte.recordbuf.plugin.model.Message m) {
        boolean needsCompact = m.fields().stream().anyMatch(f ->
                f.isOptionalWrapped() || f.isRepeated() || f.isMap());
        if (!needsCompact) return;
        w.line();
        w.line("public " + m.name() + " {");
        w.indent(w.indent() + 1);
        for (var f : m.fields()) {
            if (f.isOptionalWrapped()) {
                w.line(f.javaName() + " = " + f.javaName() + " == null ? java.util.Optional.empty() : " + f.javaName() + ";");
            } else if (f.isRepeated()) {
                w.line(f.javaName() + " = " + f.javaName() + " == null ? java.util.List.of() : java.util.List.copyOf(" + f.javaName() + ");");
            } else if (f.isMap()) {
                w.line(f.javaName() + " = " + f.javaName() + " == null ? java.util.Map.of() : java.util.Map.copyOf(" + f.javaName() + ");");
            }
        }
        w.indent(w.indent() - 1);
        w.line("}");
    }

    private String resolveJavaType(bijnagte.recordbuf.plugin.model.Message m,
                                   bijnagte.recordbuf.plugin.model.Field f,
                                   String javaPkg) {
        TypeResolver types = new TypeResolver(table, javaPkg);
        return types.resolve(f);
    }

    private FileDescriptorProto findByPath(String path) {
        return table.byName(path);
    }

    private String javaPackage(FileDescriptorProto fdp) {
        if (fdp.getOptions().hasJavaPackage() && !fdp.getOptions().getJavaPackage().isBlank()) {
            return fdp.getOptions().getJavaPackage();
        }
        if (!fdp.getPackage().isBlank()) return fdp.getPackage();
        String stem = fdp.getName();
        int slash = stem.lastIndexOf('/');
        if (slash >= 0) stem = stem.substring(slash + 1);
        int dot = stem.indexOf('.');
        if (dot >= 0) stem = stem.substring(0, dot);
        return stem;
    }
}
