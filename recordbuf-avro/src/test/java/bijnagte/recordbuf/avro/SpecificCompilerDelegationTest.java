package bijnagte.recordbuf.avro;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.StandardJavaFileManager;
import javax.tools.StandardLocation;
import javax.tools.ToolProvider;
import org.apache.avro.Schema;
import org.apache.avro.compiler.specific.SpecificCompiler;
import org.apache.avro.generic.GenericData;
import org.apache.avro.generic.GenericDatumReader;
import org.apache.avro.generic.GenericDatumWriter;
import org.apache.avro.generic.IndexedRecord;
import org.apache.avro.io.DecoderFactory;
import org.apache.avro.io.EncoderFactory;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * Proves option B (KTD6 delegation): the per-type {@code XSpecific} is NOT generated by us — we run
 * Avro's own {@link SpecificCompiler} over the per-file {@code .avsc} (U4's output) to emit a
 * {@code SpecificRecordBase} subclass with an embedded schema, and the consumed record round-trips
 * through that <em>generated</em> class via the schema-driven generic API (a {@link GenericData}
 * datum reader/writer, KTD11 -- not a per-record codec).
 *
 * <p>This is the test that replaced the deleted hand-rolled {@code AvroSpecificGenerator}: it
 * exercises the real delegation path. The generated specific record compiles against core {@code
 * avro} alone (the {@code avro-compiler} artifact is a generation-time dependency only).
 */
class SpecificCompilerDelegationTest {

  // A minimal .avsc: the kind of standalone schema U4 emits for a message with two scalar fields.
  private static final String AVSC =
      "{\n"
          + "  \"type\": \"record\",\n"
          + "  \"name\": \"Person\",\n"
          + "  \"namespace\": \"com.example\",\n"
          + "  \"fields\": [\n"
          + "    { \"name\": \"age\", \"type\": \"int\" },\n"
          + "    { \"name\": \"name\", \"type\": [\"null\", \"string\"] }\n"
          + "  ]\n"
          + "}\n";

  /**
   * Avro's {@code SpecificCompiler} turns the {@code .avsc} into a {@code SpecificRecordBase}
   * subclass that compiles + round-trips a value through the schema-driven generic API.
   */
  @Test
  void schemaCompilerEmitsACompilableSpecificRecordThatRoundTrips(@TempDir File dir)
      throws Exception {
    File avsc = new File(dir, "Person.avsc");
    Files.writeString(avsc.toPath(), AVSC);

    // Delegate the schema -\u003e specific-record generation to Avro (our one dependency on this
    // step).
    File generated = new File(dir, "gen");
    generated.mkdirs();
    SpecificCompiler compiler = new SpecificCompiler(new Schema.Parser().parse(avsc));
    compiler.compileToDestination(avsc, generated);

    File personJava = findGeneratedJava(generated, "Person.java");
    assertNotNull(personJava, "SpecificCompiler produced a source file");
    assertTrue(personJava.length() > 0, "the generated source has content");

    // Compile the generated class against the test classpath (which carries core avro).
    JavaCompiler c = ToolProvider.getSystemJavaCompiler();
    assertNotNull(c, "a system Java compiler is available (JDK)");
    DiagnosticCollector<javax.tools.JavaFileObject> dc = new DiagnosticCollector<>();
    File compileOut = new File(dir, "classes");
    compileOut.mkdirs();
    StandardJavaFileManager fm = c.getStandardFileManager(dc, null, null);
    fm.setLocation(StandardLocation.CLASS_OUTPUT, List.of(compileOut));
    var sources = fm.getJavaFileObjectsFromFiles(List.of(personJava));
    boolean ok = c.getTask(null, fm, dc, List.of(), null, sources).call();
    fm.close();
    assertTrue(
        ok, "the generated specific record compiles; diagnostics:\u200b" + dc.getDiagnostics());

    // Prove the class is a SpecificRecord and round-trips a value, schema-driven.
    // Load the compiled class from the output dir, with core avro on the parent classpath
    // (the test runtime classpath already carries org.apache.avro). Its nested Builder/helper
    // classes are sibling files in the same output dir, so the URLClassLoader resolves them too.
    ClassLoader base = getClass().getClassLoader();
    ClassLoader cl =
        new java.net.URLClassLoader(new java.net.URL[] {compileOut.toURI().toURL()}, base);
    Class<?> person = Class.forName("com.example.Person", true, cl);
    Schema schema = (Schema) person.getField("SCHEMA$").get(null);
    IndexedRecord in = new GenericData.Record(schema);
    in.put(0, 30);
    in.put(1, "Ada");
    var outBytes = new ByteArrayOutputStream();
    var encoder = EncoderFactory.get().binaryEncoder(outBytes, null);
    new GenericDatumWriter<>(schema).write(in, encoder);
    encoder.flush(); // the 1.12 binary encoder buffers; flush before reading the bytes out
    IndexedRecord back = new GenericData.Record(schema);
    new GenericDatumReader<>(schema, schema)
        .read(back, DecoderFactory.get().binaryDecoder(outBytes.toByteArray(), null));
    assertEquals(30, back.get(0));
    assertEquals(
        "Ada", String.valueOf(back.get(1))); // Avro represents strings as org.apache.avro.util.Utf8
  }

  private static File findGeneratedJava(File dir, String name) throws Exception {
    try (var s = Files.walk(dir.toPath())) {
      return s.filter(p -> p.getFileName().toString().equals(name))
          .findFirst()
          .map(Path::toFile)
          .orElseThrow();
    }
  }
}
