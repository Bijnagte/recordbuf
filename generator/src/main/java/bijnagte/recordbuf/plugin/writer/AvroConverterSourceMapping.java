package bijnagte.recordbuf.plugin.writer;

import bijnagte.recordbuf.codegen.SourceRenderer;
import bijnagte.recordbuf.codegen.TypeCollector;
import bijnagte.recordbuf.codegen.source.ClassSpec;
import bijnagte.recordbuf.codegen.source.Constructor;
import bijnagte.recordbuf.codegen.source.Element;
import bijnagte.recordbuf.codegen.source.Formatter;
import bijnagte.recordbuf.codegen.source.JavaFile;
import bijnagte.recordbuf.codegen.source.LocalVar;
import bijnagte.recordbuf.codegen.source.Method;
import bijnagte.recordbuf.codegen.source.RawExpr;
import bijnagte.recordbuf.codegen.source.TypeRef;
import bijnagte.recordbuf.plugin.model.Field;
import bijnagte.recordbuf.plugin.model.FieldKind;
import bijnagte.recordbuf.plugin.model.Message;
import java.util.List;
import java.util.Set;

/**
 * Maps a top-level message's Avro {@code <X>AvroConverter} (record ↔ Avro-specific-record
 * conversion) through the source-AST, replacing the former string-concatenation implementation with
 * a {@link ClassSpec} + {@link SourceRenderer} pipeline.
 *
 * <p>The converter handles both directions of a round-trip:
 *
 * <ul>
 *   <li>{@code toRecord(<X>Avro s)}: calls the recordbuf record's fluent builder, setting each
 *       field via its setter; Avro getters route scalars/bytes directly and WKT fields route
 *       through {@link bijnagte.recordbuf.avro.WktAvroBridge#fromAvro}.
 *   <li>{@code fromRecord(<X> r)}: creates a fresh Avro specific record, populating each field via
 *       its setter; WKT fields route through {@link bijnagte.recordbuf.avro.WktAvroBridge#toAvro}.
 * </ul>
 */
public final class AvroConverterSourceMapping {

  private AvroConverterSourceMapping() {}

  /**
   * Generate the Avro-interop converter class for {@code message}, returning the rendered Java
   * source string.
   *
   * @param protoRoot the recordbuf record and converter-class base name (e.g. {@code Sample})
   * @param protoFile the {@code recordbuf.proto} filename, for the source header
   * @param message the top-level message to generate a converter for
   * @param specificRecordPkg the package of the generated Avro specific record class
   * @param recordPkg the package of the recordbuf record (and this converter class)
   * @return the generated source string
   */
  public static String generate(
      String protoRoot,
      String protoFile,
      Message message,
      String specificRecordPkg,
      String recordPkg,
      Formatter formatter) {
    TypeRef recordClass = TypeRef.of(protoRoot);
    TypeRef avroSpecific = TypeRef.of(protoRoot + "Avro");

    TypeCollector ci = new TypeCollector(recordPkg);

    // --- the Avro specific-record FQN travels via the JavaFile side channel (externalRefs), not a
    // TypeCollector registration: it is an import the converter needs only when the specific record
    // lives in a different package. The renderer aggregates it into the collect pass. ---
    boolean samePkg = recordPkg.equals(specificRecordPkg);
    Set<TypeRef> externalRefs =
        samePkg ? Set.of() : Set.of(TypeRef.of(specificRecordPkg + "." + avroSpecific.shortName()));

    // --- class AST ---
    Constructor privateCtor = Constructor.builder().private_().body().build();

    Method toRecord = buildToRecord(message, recordClass, avroSpecific);
    Method fromRecord = buildFromRecord(message, recordClass, avroSpecific);

    ClassSpec converterClass =
        ClassSpec.named(recordClass.shortName() + "AvroConverter")
            .public_()
            .final_()
            .javadoc(GeneratedDocs.type(recordClass.shortName(), "Avro converter for the %s type."))
            .constructor(privateCtor)
            .method(toRecord, fromRecord)
            .build();

    JavaFile javaFile = new JavaFile(recordPkg, null, converterClass, ci, externalRefs);
    String rendered = SourceRenderer.render(javaFile, formatter);

    // Prepend the generated-file comment block.
    String comment =
        "/*\n * Generated by recordbuf -- DO NOT EDIT.\n"
            + " * Converter for "
            + protoFile
            + " record \u2194 Avro specific record.\n */\n\n";
    return comment + rendered;
  }

  // --- toRecord body builder ----------------------------------------------------------

  private static Method buildToRecord(Message message, TypeRef recordClass, TypeRef avroSpecific) {
    var method =
        Method.named("toRecord")
            .public_()
            .static_()
            .returnType(recordClass)
            .param(avroSpecific, "s")
            .body(
                LocalVar.builder(builderType(recordClass), "b")
                    .assigned(RawExpr.of("@0.builder()", recordClass)));
    for (Field f : message.fields()) {
      method.body(toRecordFieldLine(f, "s"));
    }
    return method
        .body(Element.expr("@0.unknownFields(@1.empty())", "b", TypeRefs.UNKNOWN_FIELDS))
        .body(Element.ret("b.build()"))
        .build();
  }

  private static Element toRecordFieldLine(Field f, String param) {
    String getter = param + ".get" + cap(f.javaName());
    String var = "b." + f.javaName();
    if (AvroSchemaGenerator.typeUrlIfWkt(f) != null) {
      return Element.expr("@0(@1.fromAvro(@2()))", var, TypeRefs.WKT_AVRO_BRIDGE, getter);
    }
    if (f.kind() == FieldKind.SCALAR && "bytes".equals(f.typeUrl())) {
      return Element.expr(
          "@0(@1() != null ? @2.of(@3.copyOf(@1().array(), @1().remaining())) : @2.empty())",
          var,
          getter,
          TypeRefs.BYTES,
          TypeRefs.ARRAYS);
    }
    if (f.kind() == FieldKind.SCALAR && "string".equals(f.typeUrl())) {
      return Element.expr("@0(@1().toString())", var, getter);
    }
    return Element.expr("@0(@1())", var, getter);
  }

  // --- fromRecord body builder --------------------------------------------------------

  private static Method buildFromRecord(
      Message message, TypeRef recordClass, TypeRef avroSpecific) {

    var method =
        Method.named("fromRecord")
            .public_()
            .static_()
            .returnType(avroSpecific)
            .param(recordClass, "r")
            .body(
                LocalVar.builder(avroSpecific, "s").assigned(RawExpr.of("new @0()", avroSpecific)))
            .body(Element.of("")); // blank line between declaration and setters

    for (Field f : message.fields()) {
      method.body(fromRecordFieldLine(f, "s", "r"));
    }

    return method.body(Element.ret("s")).build();
  }

  private static Element fromRecordFieldLine(Field f, String param, String record) {
    String setter = param + ".set" + cap(f.javaName());
    String accessor = record + "." + f.javaName() + "()";
    if (AvroSchemaGenerator.typeUrlIfWkt(f) != null) {
      return Element.expr("@0(@1.toAvro(@2))", setter, TypeRefs.WKT_AVRO_BRIDGE, accessor);
    }
    if (f.kind() == FieldKind.SCALAR && "bytes".equals(f.typeUrl())) {
      return Element.expr("@0(@1.wrap(@2.toByteArray()))", setter, TypeRefs.BYTE_BUFFER, accessor);
    }
    return Element.expr("@0(@1)", setter, accessor);
  }

  /** The record's nested builder type — e.g. {@code Sample.Builder} for record {@code Sample}. */
  private static TypeRef builderType(TypeRef recordClass) {
    return TypeRef.named("", recordClass.shortName() + ".Builder", List.of());
  }

  private static String cap(String s) {
    return s.isEmpty() ? s : Character.toUpperCase(s.charAt(0)) + s.substring(1);
  }
}
