package bijnagte.recordbuf.plugin.writer;

import bijnagte.recordbuf.codegen.TypeCollector;
import bijnagte.recordbuf.codegen.source.JavaFile;
import bijnagte.recordbuf.codegen.source.Line;
import bijnagte.recordbuf.codegen.source.Member;
import bijnagte.recordbuf.codegen.source.SourceRenderer;
import bijnagte.recordbuf.codegen.source.Type;
import bijnagte.recordbuf.plugin.model.Field;
import bijnagte.recordbuf.plugin.model.FieldKind;
import bijnagte.recordbuf.plugin.model.Message;
import java.util.ArrayList;
import java.util.List;

/**
 * Maps a top-level message's Avro {@code <X>AvroConverter} (record ↔ Avro-specific-record
 * conversion) through the source-AST, replacing the former string-concatenation implementation with
 * a {@link Type.Class} + {@link SourceRenderer} pipeline.
 *
 * <p>The converter handles both directions of a round-trip:
 *
 * <ul>
 *   <li>{@code toRecord(<X>Avro s)}: calls the recordbuf record's fluent builder, setting each
 *       field via its setter; Avro getters route scalars/bytes directly and WKT fields route
 *       through {@link bijnagte.recordbuf.avro.WktAvroBridge#fromAvro}.
 *   <li>{@code fromRecord(<X> r)}: creates a fresh Avro specific record, populating each field via
 *       its setter; WKT fields route through {@link bijnagte.recordbuf.avro.WktAvroBridge#toAvro}.
 * </ul>
 */
public final class AvroConverterSourceMapping {

  private AvroConverterSourceMapping() {}

  // Suppression annotation rendered on the class declaration.
  private static final List<String> ANNOTATIONS =
      List.of(
          "@SuppressWarnings({\"checkstyle:HideUtilityClassConstructor\", \"checkstyle:MissingJavadoc\"})");

  /**
   * Generate the Avro-interop converter class for {@code message}, returning the rendered Java
   * source string.
   *
   * @param protoRoot the recordbuf record and converter-class base name (e.g. {@code Sample})
   * @param protoFile the {@code recordbuf.proto} filename, for the source header
   * @param message the top-level message to generate a converter for
   * @param specificRecordPkg the package of the generated Avro specific record class
   * @param recordPkg the package of the recordbuf record (and this converter class)
   * @return the generated source string
   */
  public static String generate(
      String protoRoot,
      String protoFile,
      Message message,
      String specificRecordPkg,
      String recordPkg) {
    String recordClass = protoRoot;
    String avroSpecific = protoRoot + "Avro";

    TypeCollector ci = new TypeCollector(recordPkg);

    // --- conditional imports, resolved upfront in the TypeCollector ---
    boolean samePkg = recordPkg.equals(specificRecordPkg);
    if (!samePkg) {
      ci.use(specificRecordPkg + "." + avroSpecific);
    }
    boolean hasWkt =
        message.fields().stream().anyMatch(f -> AvroSchemaGenerator.typeUrlIfWkt(f) != null);
    if (hasWkt) {
      ci.use("bijnagte.recordbuf.avro.WktAvroBridge");
    }
    boolean hasByteField =
        message.fields().stream()
            .anyMatch(f -> f.kind() == FieldKind.SCALAR && "bytes".equals(f.typeUrl()));
    if (hasByteField) {
      ci.use("bijnagte.recordbuf.runtime.Bytes");
      ci.use("java.nio.ByteBuffer");
      ci.use("java.util.Arrays");
    }
    ci.use("bijnagte.recordbuf.runtime.UnknownFields");

    // --- class AST ---
    Member privateCtor =
        Member.Constructor.builder()
            .name(recordClass + "AvroConverter")
            .private_()
            .params("()")
            .body(List.of())
            .build();

    Member toRecord = buildToRecord(message, recordClass, avroSpecific, hasWkt, hasByteField);
    Member fromRecord = buildFromRecord(message, recordClass, avroSpecific, hasWkt);

    Type.Class converterClass =
        Type.Class.builder()
            .name(recordClass + "AvroConverter")
            .public_()
            .final_()
            .annotations(ANNOTATIONS)
            .members(List.of(privateCtor, toRecord, fromRecord))
            .build();

    JavaFile javaFile = new JavaFile(recordPkg, null, converterClass, ci);
    String rendered = SourceRenderer.render(javaFile);

    // Prepend the generated-file comment block.
    String comment =
        "/*\n * Generated by recordbuf -- DO NOT EDIT.\n"
            + " * Converter for "
            + protoFile
            + " record \u2194 Avro specific record.\n */\n\n";
    return comment + rendered;
  }

  // --- toRecord body builder ----------------------------------------------------------

  private static Member buildToRecord(
      Message message,
      String recordClass,
      String avroSpecific,
      boolean hasWkt,
      boolean hasByteField) {
    List<Line> body = new ArrayList<>();
    body.add(Line.of(recordClass + ".Builder b = " + recordClass + ".builder();"));
    for (Field f : message.fields()) {
      body.add(toRecordFieldLine(f, "s", hasWkt, hasByteField));
    }
    body.add(Line.of("b.unknownFields(UnknownFields.empty());"));
    body.add(Line.of("return b.build();"));

    return Member.Method.builder()
        .public_()
        .static_()
        .returnType(recordClass)
        .name("toRecord")
        .params("(" + avroSpecific + " s)")
        .body(body)
        .build();
  }

  private static Line toRecordFieldLine(
      Field f, String param, boolean hasWkt, boolean hasByteField) {
    String getter = param + ".get" + cap(f.javaName());
    String var = "b." + f.javaName();
    if (AvroSchemaGenerator.typeUrlIfWkt(f) != null) {
      return Line.of(var + "(WktAvroBridge.fromAvro(" + getter + "());");
    }
    if (f.kind() == FieldKind.SCALAR && "bytes".equals(f.typeUrl())) {
      return Line.of(
          var
              + "("
              + getter
              + "() != null ? Bytes.of(Arrays.copyOf("
              + getter
              + "().array(), "
              + getter
              + "().remaining())) : Bytes.empty());");
    }
    if (f.kind() == FieldKind.SCALAR && "string".equals(f.typeUrl())) {
      return Line.of(var + "(" + getter + "().toString());");
    }
    return Line.of(var + "(" + getter + "());");
  }

  // --- fromRecord body builder --------------------------------------------------------

  private static Member buildFromRecord(
      Message message, String recordClass, String avroSpecific, boolean hasWkt) {
    List<Line> body = new ArrayList<>();
    body.add(Line.of(avroSpecific + " s = new " + avroSpecific + "();"));
    body.add(Line.of("")); // blank line between declaration and setters
    for (Field f : message.fields()) {
      body.add(fromRecordFieldLine(f, "s", "r", hasWkt));
    }
    body.add(Line.of("return s;"));

    return Member.Method.builder()
        .public_()
        .static_()
        .returnType(avroSpecific)
        .name("fromRecord")
        .params("(" + recordClass + " r)")
        .body(body)
        .build();
  }

  private static Line fromRecordFieldLine(Field f, String param, String record, boolean hasWkt) {
    String setter = param + ".set" + cap(f.javaName());
    String accessor = record + "." + f.javaName() + "()";
    if (AvroSchemaGenerator.typeUrlIfWkt(f) != null) {
      return Line.of(setter + "(WktAvroBridge.toAvro(" + accessor + "));");
    }
    if (f.kind() == FieldKind.SCALAR && "bytes".equals(f.typeUrl())) {
      return Line.of(setter + "(ByteBuffer.wrap(" + accessor + ".toByteArray()));");
    }
    return Line.of(setter + "(" + accessor + ");");
  }

  private static String cap(String s) {
    return s.isEmpty() ? s : Character.toUpperCase(s.charAt(0)) + s.substring(1);
  }
}
