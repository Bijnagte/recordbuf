package bijnagte.recordbuf.plugin.writer;

import bijnagte.recordbuf.codegen.source.Javadoc;
import org.jspecify.annotations.Nullable;

/**
 * Builds the uniform, type-level Javadoc recordbuf emits on its generated types.
 *
 * <p>The result is either the proto's own comment (when present) or a generated fallback: the fixed
 * {@link #MARKER} line followed by a short, type-specific {@code description}. Every generated type
 * (record, enum, enum constant, and the derived Builder / Codec / Interop / builder / build) routes
 * its type-level Javadoc through {@link #type}, so the marker is uniform across the generated
 * output and a generated type is never Javadoc-less.
 */
final class GeneratedDocs {

  /** The fixed generated-code marker, mirroring the file-level "Generated by" header. */
  static final String MARKER = "Generated by recordbuf -- DO NOT EDIT.";

  private GeneratedDocs() {}

  /**
   * The type-level Javadoc: the proto comment when present, else {@link #MARKER} plus a
   * type-specific {@code description}. Pass a {@code null} (or blank) {@code protoComment} for a
   * derived type that has no proto comment of its own (Builder, Codec, Interop, builder, build) --
   * those always take the marker + description branch.
   */
  static Javadoc type(@Nullable String protoComment, String description) {
    if (protoComment != null && !protoComment.isBlank()) {
      return Javadoc.builder().text(protoComment).build();
    }
    return Javadoc.builder().text(MARKER, "\n", description).build();
  }
}
