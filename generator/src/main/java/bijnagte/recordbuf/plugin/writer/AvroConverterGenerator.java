package bijnagte.recordbuf.plugin.writer;

import bijnagte.recordbuf.plugin.model.Field;
import bijnagte.recordbuf.plugin.model.FieldKind;
import bijnagte.recordbuf.plugin.model.Message;

/**
 * Generates the {@link bijnagte.recordbuf.plugin.bridge.AvroBridge} converter class ({@code
 * <X>Avro}) for one top-level message.
 *
 * <p>The converter handles both directions of a round-trip:
 *
 * <ul>
 *   <li>{@code toRecord(<X>Avro s)}: calls the recordbuf record's fluent builder ({@code
 *       .builder()}, setting each field via its setter), then {@code .build()}. Avro getters route
 *       scalars/bytes directly; WKT fields route through {@link
 *       bijnagte.recordbuf.plugin.bridge.WktAvroBridge#fromAvro}. The record's {@code
 *       UnknownFields} component is always set to {@code UnknownFields.empty()} (unknown fields are
 *       a protobuf-only concept).
 *   <li>{@code fromRecord(<X> r)}: creates a fresh Avro specific record via its no-arg constructor
 *       and populates each field via its setter. Scalars/bytes call the setter directly; WKT fields
 *       route through {@link bijnagte.recordbuf.plugin.bridge.WktAvroBridge#toAvro}.
 * </ul>
 */
public final class AvroConverterGenerator {
  private AvroConverterGenerator() {}

  /**
   * Generates the full converter class for {@code protoRoot}/{@code protoFile}.
   *
   * @param protoRoot the {@code recordbuf.proto} root; its {@code .name} is the recordbuf record
   *     and converter class base name
   * @param protoFile the {@code recordbuf.proto} filename
   * @param message the top-level message (one-per-file invariant)
   * @param specificRecordPkg the package of the Avro specific record -- the {@code
   *     recordbuf.proto}'s natural (un-suffixed) package, computed by the Avro bridge's
   *     record-package helper; the specific record class name is {@code <protoRoot.name>Avro}
   * @param converterPkg the package of the generated converter — the recordbuf record's own package
   *     (the {@code .rec}-suffixed package where {@code Sample.java} lives). Keeps the record type
   *     resolvable as a short name.
   * @return generated source
   */
  public static String generate(
      String protoRoot,
      String protoFile,
      Message message,
      String specificRecordPkg,
      String converterPkg) {
    String recordClass = protoRoot;
    String avroSpecific = protoRoot + "Avro";
    StringBuilder sb = new StringBuilder(512);
    sb.append("/*\n * Generated by recordbuf -- DO NOT EDIT.\n");
    sb.append(" * Converter for ")
        .append(protoFile)
        .append(" record ↔ Avro specific record.\n */\n\n");
    if (!converterPkg.isEmpty()) {
      sb.append("package ").append(converterPkg).append(";\n\n");
    }
    // Only import the specific record when it lives in a different package.
    boolean samePkg = converterPkg.equals(specificRecordPkg);
    if (!samePkg) {
      sb.append("import ").append(specificRecordPkg).append('.').append(avroSpecific).append(";\n");
    }
    // Only import WktAvroBridge (in a different module's package) when a WKT field is present.
    boolean hasWkt =
        message.fields().stream().anyMatch(f -> AvroSchemaGenerator.typeUrlIfWkt(f) != null);
    if (hasWkt) {
      sb.append("import bijnagte.recordbuf.avro.WktAvroBridge;\n");
    }
    sb.append("import bijnagte.recordbuf.runtime.UnknownFields;\n\n");
    sb.append(
        "@SuppressWarnings({\"checkstyle:HideUtilityClassConstructor\", \"checkstyle:MissingJavadoc\"})\n");
    sb.append("public final class ").append(recordClass).append("AvroConverter {\n");
    sb.append("    private ").append(recordClass).append("AvroConverter() {}\n\n");

    toRecord(sb, message, recordClass, avroSpecific);
    fromRecord(sb, message, recordClass, avroSpecific);

    sb.append("}\n");
    return sb.toString();
  }

  private static void toRecord(
      StringBuilder sb, Message message, String recordClass, String avroSpecific) {
    sb.append("    public static ")
        .append(recordClass)
        .append(" toRecord(")
        .append(avroSpecific)
        .append(" s) {\n");
    sb.append("        ")
        .append(recordClass)
        .append(".Builder b = ")
        .append(recordClass)
        .append(".builder();\n");
    for (Field f : message.fields()) {
      String getter = "s.get" + cap(f.javaName());
      if (AvroSchemaGenerator.typeUrlIfWkt(f) != null) {
        sb.append("        b.")
            .append(f.javaName())
            .append("(WktAvroBridge.fromAvro(")
            .append(getter)
            .append("()));\n");
      } else if (f.kind() == FieldKind.SCALAR && "bytes".equals(f.typeUrl())) {
        // Avro's specific record stores bytes as a ByteBuffer; convert to byte[].
        sb.append("        b.")
            .append(f.javaName())
            .append("(")
            .append(getter)
            .append("() != null ? ")
            .append("java.util.Arrays.copyOf(")
            .append(getter)
            .append("().array(), ")
            .append(getter)
            .append("().remaining()) : new byte[0]);\n");
      } else if (f.kind() == FieldKind.SCALAR && "string".equals(f.typeUrl())) {
        // Avro 1.12 specific records store string fields as CharSequence (Utf8); call toString() so
        // the recordbuilder's String-typed field resolves.
        sb.append("        b.")
            .append(f.javaName())
            .append("(")
            .append(getter)
            .append("().toString());\n");
      } else {
        sb.append("        b.").append(f.javaName()).append("(").append(getter).append("());\n");
      }
    }
    sb.append("        b.unknownFields(UnknownFields.empty());\n");
    sb.append("        return b.build();\n");
    sb.append("    }\n\n");
  }

  private static void fromRecord(
      StringBuilder sb, Message message, String recordClass, String avroSpecific) {
    sb.append("    public static ")
        .append(avroSpecific)
        .append(" fromRecord(")
        .append(recordClass)
        .append(" r) {\n");
    sb.append("        ")
        .append(avroSpecific)
        .append(" s = new ")
        .append(avroSpecific)
        .append("();\n\n");
    for (Field f : message.fields()) {
      String setter = "s.set" + cap(f.javaName());
      String accessor = "r." + f.javaName() + "()";
      if (AvroSchemaGenerator.typeUrlIfWkt(f) != null) {
        sb.append("        ")
            .append(setter)
            .append("(WktAvroBridge.toAvro(")
            .append(accessor)
            .append("));\n");
      } else if (f.kind() == FieldKind.SCALAR && "bytes".equals(f.typeUrl())) {
        // Record's byte[] → Avro's ByteBuffer via ByteBuffer.wrap.
        sb.append("        ")
            .append(setter)
            .append("(java.nio.ByteBuffer.wrap(")
            .append(accessor)
            .append("));\n");
      } else {
        sb.append("        ").append(setter).append("(").append(accessor).append(");\n");
      }
    }
    sb.append("        return s;\n");
    sb.append("    }\n");
  }

  private static String cap(String s) {
    return s.isEmpty() ? s : Character.toUpperCase(s.charAt(0)) + s.substring(1);
  }
}
