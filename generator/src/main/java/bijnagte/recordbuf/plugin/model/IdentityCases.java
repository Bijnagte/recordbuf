package bijnagte.recordbuf.plugin.model;

import bijnagte.recordbuf.codegen.source.TypeRef;
import bijnagte.recordbuf.plugin.types.WellKnownTypes;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.jspecify.annotations.NullMarked;

/**
 * The identity-subtype rule for oneof cases: decides, per (oneof, case) pair, whether a case's
 * generated message or enum is itself the sealed-interface subtype rather than wrapped in a {@code
 * <Cap>Value} record.
 *
 * <p>A case is an identity subtype iff all of:
 *
 * <ol>
 *   <li>its member is a generated message or enum (never a scalar, and never a well-known type
 *       whose Java form is not generated by recordbuf);
 *   <li>the file declaring the oneof and the file declaring the case type are both in this
 *       invocation's {@code file_to_generate};
 *   <li>the case type's Java package equals the Java package of the oneof's sealed interface.
 * </ol>
 *
 * <p>Every writer evaluates the same predicate on the same pair, so the case type's {@code
 * implements} clause and the interface's {@code permits} clause always agree, even when generation
 * is split across protoc invocations (a pair whose files are not both in the run falls back to the
 * wrapper on both sides).
 *
 * <p>Results are sorted, so the output does not depend on the order of the request's files.
 */
@NullMarked
public final class IdentityCases {

  /** One oneof-member occurrence: the file that declares the oneof, the oneof, and the member. */
  private record Occurrence(String oneofFile, Oneof oneof, Field member) {}

  private final FileTable table;
  private final Collection<String> generating;

  /** Case type's Java FQN -> every oneof occurrence that lists that type as a member. */
  private final Map<String, List<Occurrence>> byCaseType;

  private IdentityCases(
      FileTable table, Collection<String> generating, Map<String, List<Occurrence>> byCaseType) {
    this.table = table;
    this.generating = generating;
    this.byCaseType = byCaseType;
  }

  /**
   * A predicate under which no case is an identity subtype: the wrapper shape, used when a loader
   * is not part of a generation run.
   *
   * @param table the type table, unused by the empty predicate but kept so every caller holds the
   *     same shape
   */
  public static IdentityCases none(FileTable table) {
    return new IdentityCases(table, List.of(), Map.of());
  }

  /**
   * Index every oneof member of the files being generated in this run.
   *
   * @param table the run-wide type table, used to resolve the case type's declaring file
   * @param generated the loaded models of the files in {@code file_to_generate}, keyed by file name
   */
  public static IdentityCases of(FileTable table, Map<String, ProtoFile> generated) {
    Map<String, List<Occurrence>> byCaseType = new LinkedHashMap<>();
    for (ProtoFile pf : generated.values()) {
      for (Message m : pf.messages()) {
        index(pf.fileName(), m, byCaseType);
      }
    }
    return new IdentityCases(table, List.copyOf(generated.keySet()), byCaseType);
  }

  private static void index(String file, Message m, Map<String, List<Occurrence>> out) {
    for (Oneof oneof : m.oneofs()) {
      for (Field member : oneof.members()) {
        out.computeIfAbsent(member.type().fqn(), k -> new ArrayList<>())
            .add(new Occurrence(file, oneof, member));
      }
    }
    for (Message nested : m.nestedMessages()) {
      index(file, nested, out);
    }
  }

  /**
   * Whether {@code member}, a case of a oneof declared in {@code oneofFile} whose sealed interface
   * is {@code iface}, is an identity subtype.
   *
   * @param oneofFile the file name that declares the oneof
   * @param iface the oneof's sealed interface
   * @param member the case
   */
  public boolean isIdentity(String oneofFile, TypeRef.Named iface, Field member) {
    if (member.kind() != FieldKind.MESSAGE && member.kind() != FieldKind.ENUM) {
      return false;
    }
    if (WellKnownTypes.resolve(member.typeUrl()) != null) {
      return false;
    }
    if (!generating.contains(oneofFile)) {
      return false;
    }
    String memberFile = table.fileNameOf(member.typeUrl());
    if (memberFile == null || !generating.contains(memberFile)) {
      return false;
    }
    String memberPkg = table.javaPackageOf(member.type().fqn());
    return memberPkg != null && memberPkg.equals(iface.pkg());
  }

  /**
   * The sealed interfaces that a generated case type must implement, sorted by fully-qualified
   * name. Empty when the type is not an identity case of any oneof in this run.
   *
   * @param caseTypeJavaFqn the case type's Java FQN, as {@link TypeRef#fqn()} renders it
   */
  public List<TypeRef.Named> implementedBy(String caseTypeJavaFqn) {
    List<Occurrence> occurrences = byCaseType.getOrDefault(caseTypeJavaFqn, List.of());
    List<TypeRef.Named> out = new ArrayList<>();
    for (Occurrence o : occurrences) {
      if (isIdentity(o.oneofFile(), o.oneof().iface(), o.member())) {
        out.add(o.oneof().iface());
      }
    }
    out.sort(Comparator.comparing(TypeRef::fqn));
    return out.stream().distinct().toList();
  }
}
