package bijnagte.recordbuf.plugin;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.protobuf.DescriptorProtos.DescriptorProto;
import com.google.protobuf.DescriptorProtos.FieldDescriptorProto;
import com.google.protobuf.DescriptorProtos.FieldDescriptorProto.Label;
import com.google.protobuf.DescriptorProtos.FieldDescriptorProto.Type;
import com.google.protobuf.DescriptorProtos.FileDescriptorProto;
import com.google.protobuf.compiler.PluginProtos.CodeGeneratorRequest;
import com.google.protobuf.compiler.PluginProtos.CodeGeneratorResponse;
import com.google.protobuf.compiler.PluginProtos.CodeGeneratorResponse.File;
import java.util.List;
import org.junit.jupiter.api.Test;

/**
 * U1 (feat-nullaway-generated-code): every recordbuf-generated java package carries an emitted
 * {@code package-info.java} marked {@code @NullMarked}, once per package across the request (de-dup
 * when several .proto files share a package), so a consumer running NullAway with {@code
 * OnlyNullMarked=true} checks the generated records and skips the un-marked protobuf-java reference
 * output. These source-shape assertions lock the emitter; the fixtures {@code compileJava}/{@code
 * test} confirm the emitted package-info is well-formed and scopes the check, which a JVM unit test
 * cannot reach alone.
 */
@SuppressWarnings("BadImport")
class PackageInfoEmissionTest {

  private static FileDescriptorProto file(String name, String pkg, DescriptorProto... messages) {
    FileDescriptorProto.Builder fd = FileDescriptorProto.newBuilder().setName(name).setPackage(pkg);
    for (DescriptorProto m : messages) fd.addMessageType(m);
    return fd.build();
  }

  private static DescriptorProto message(String name, FieldDescriptorProto... fields) {
    DescriptorProto.Builder m = DescriptorProto.newBuilder().setName(name);
    for (FieldDescriptorProto f : fields) m.addField(f);
    return m.build();
  }

  private static FieldDescriptorProto intField(String name, int number) {
    return FieldDescriptorProto.newBuilder()
        .setName(name)
        .setNumber(number)
        .setLabel(Label.LABEL_OPTIONAL)
        .setType(Type.TYPE_INT32)
        .build();
  }

  private static List<CodeGeneratorResponse.File> generate(
      FileDescriptorProto fd, String fileToGen) {
    return new CodeGenerator()
        .generate(
            CodeGeneratorRequest.newBuilder().addProtoFile(fd).addFileToGenerate(fileToGen).build())
        .getFileList();
  }

  /** Run a request whose {@code file_to_generate} lists {@code fileNames} in order. */
  private static List<CodeGeneratorResponse.File> generate(
      List<FileDescriptorProto> files, String... fileNames) {
    CodeGeneratorRequest.Builder req = CodeGeneratorRequest.newBuilder();
    for (FileDescriptorProto f : files) req.addProtoFile(f);
    for (String n : fileNames) req.addFileToGenerate(n);
    return new CodeGenerator().generate(req.build()).getFileList();
  }

  private static String packageInfo(List<CodeGeneratorResponse.File> out) {
    List<File> infos = out.stream().filter(f -> f.getName().endsWith("package-info.java")).toList();
    assertEquals(1, infos.size(), "exactly one package-info expected: " + infos);
    return infos.get(0).getContent();
  }

  // Single-message proto: one package-info in its package, carrying @NullMarked + import + header.
  // Covers R5.
  @Test
  void singleMessagePackageGetsOneNullMarkedPackageInfo() {
    FileDescriptorProto fd =
        file("plain.proto", "com.example", message("Sample", intField("id", 1)));
    List<CodeGeneratorResponse.File> out = generate(fd, "plain.proto");

    List<File> infos = out.stream().filter(f -> f.getName().endsWith("package-info.java")).toList();
    assertEquals(1, infos.size(), "one package-info per package: " + out);
    // Emitted into the same out-dir as the record/enum files.
    assertEquals("com/example/package-info.java", infos.get(0).getName(), "out-dir placement");

    String c = infos.get(0).getContent();
    assertTrue(c.contains("@NullMarked"), "package-info must carry the mark: " + c);
    assertTrue(c.contains("package com.example;"), "must mark the package: " + c);
    assertTrue(
        c.contains("import org.jspecify.annotations.NullMarked;"),
        "the mark import must be present: " + c);
    assertTrue(
        c.contains("Generated by recordbuf -- DO NOT EDIT."),
        "must carry the generated-file header: " + c);
    // JSpecify module convention: the annotation precedes the package element.
    assertTrue(
        c.indexOf("@NullMarked") < c.indexOf("package com.example;"),
        "annotation must precede the package element: " + c);
  }

  // A file declaring several top-level types in one package yields one package-info (not one per
  // type). Covers R5 + per-package de-dup KTD.
  @Test
  void multipleTopLevelTypesInOnePackageShareOnePackageInfo() {
    FileDescriptorProto fd =
        file(
            "multi.proto",
            "com.example",
            message("Sample", intField("a", 1)),
            message("Item", intField("n", 1)));
    List<CodeGeneratorResponse.File> out = generate(fd, "multi.proto");

    List<File> infos = out.stream().filter(f -> f.getName().endsWith("package-info.java")).toList();
    assertEquals(1, infos.size(), "one package-info for the whole package, not per type: " + out);
    assertEquals("com/example/package-info.java", infos.get(0).getName(), "out-dir placement");

    // The two records are emitted as their own files alongside the single package-info.
    long records = out.stream().filter(f -> f.getName().equals("com/example/Sample.java")).count();
    assertEquals(1, records, "the Sample record file is emitted: " + out);
  }

  // Two different .proto files mapping to the same java package yield one package-info across the
  // whole request, not two. Covers R5 + per-package de-dup KTD.
  @Test
  void twoFilesSharingAPackageProduceOnePackageInfo() {
    FileDescriptorProto a = file("alpha.proto", "com.example", message("Alpha", intField("a", 1)));
    FileDescriptorProto b = file("beta.proto", "com.example", message("Beta", intField("b", 1)));

    List<CodeGeneratorResponse.File> out = generate(List.of(a, b), "alpha.proto", "beta.proto");

    List<File> infos = out.stream().filter(f -> f.getName().endsWith("package-info.java")).toList();
    assertEquals(1, infos.size(), "de-dup across files: one package-info for the package: " + out);
    assertEquals("com/example/package-info.java", infos.get(0).getName(), "out-dir placement");

    // Both producer files' records are emitted; the package-info is not reproduced per file.
    assertTrue(
        out.stream().map(File::getName).anyMatch(n -> n.equals("com/example/Alpha.java")),
        "Alpha.java must be emitted: " + out);
    assertTrue(
        out.stream().map(File::getName).anyMatch(n -> n.equals("com/example/Beta.java")),
        "Beta.java must be emitted: " + out);
  }

  // A second request (a fresh CodeGenerator, as Main invokes one per request) regenerates the
  // package-info: per-request de-dup must not leak across calls. Covers R5 + per-call
  // statelessness.
  @Test
  void packageInfoIsEmittedFreshPerRequest() {
    FileDescriptorProto fd =
        file("plain.proto", "com.example", message("Sample", intField("id", 1)));

    assertFalse(
        packageInfo(generate(fd, "plain.proto")).isEmpty(), "first request emits a package-info");
    // A brand-new generator (fresh de-dup set) emits the package-info again for the same package.
    assertFalse(
        packageInfo(generate(fd, "plain.proto")).isEmpty(),
        "a fresh request re-emits the package-info (de-dup is per-request, not global)");
  }

  // A type-less file -- e.g. the options proto, which declares only extensions -- generates no
  // record/enum files, so it emits no package-info: a generated-output package is one that
  // actually carries a type, not a package a type-less file merely routes through. Covers R5
  // (the scope stays tight: no empty @NullMarked package enters the user's output).
  @Test
  void typeLessFileProducesNoPackageInfo() {
    FileDescriptorProto fdp =
        FileDescriptorProto.newBuilder().setName("empty.proto").setPackage("com.example").build();
    List<CodeGeneratorResponse.File> out = generate(fdp, "empty.proto");

    List<File> infos = out.stream().filter(f -> f.getName().endsWith("package-info.java")).toList();
    assertEquals(0, infos.size(), "a type-less file generates no package-info:");
  }
}
